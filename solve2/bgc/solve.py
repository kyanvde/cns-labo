from Crypto.Util.number import long_to_bytes
import gmpy2


def crt(residues, moduli):
    N = 1
    for n in moduli:
        N *= n
    x = 0
    for r, n in zip(residues, moduli):
        Ni = N // n
        x += r * Ni * pow(Ni, -1, n)
    return x % N


def hastad(cs, ns, e):
    C = crt(cs, ns)  # C = m^e mod (n1*n2*...*ne)
    m, exact = gmpy2.iroot(C, e)
    assert exact
    return int(m)


