def k_reuse_enc(c2_known, m_known, c2_target, p):
    # same k used twice (c1 identical). Recover m_target from a known plaintext.
    # c2 = m * h^k, so m_target = m_known * c2_target / c2_known
    return m_known * c2_target % p * pow(c2_known, -1, p) % p


